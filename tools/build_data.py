T0 = pd.Timestamp("2026-11-01T00:00:00Z")


def write_js(name, obj, note):
    txt = json.dumps(obj, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    js = (f"/* {note} -- generated by build_data.py from the ADA Hack 2026 data package"
          f" (github.com/vidacex/ARSOhack). Vir: ARSO. */\n"
          f"(window.LjData=window.LjData||{{}}).{name}={txt};\n")
    (OUT / f"{name}.js").write_text(js, encoding="utf-8")
    print(f"{name}.js  {len(js)/1024:.0f} KB")


def r1(v):
    return None if v is None or not np.isfinite(v) else round(float(v), 1)


def hour_index(series_time):
    t = pd.to_datetime(series_time, utc=True)
    return ((t - T0) / pd.Timedelta(hours=1)).astype(int)


