while lat < north - 1e-9:
    lng = west
    while lng < east - 1e-9:
        cl, ct = lng + dlng / 2, lat + dlat / 2
        col = int((cl - tr.c) / tr.a); row = int((ct - tr.f) / tr.e)
        win = dem[max(row - 2, 0):row + 3, max(col - 2, 0):col + 3]
        if win.size and np.isfinite(win).any():
            hgt = float(np.nanmedian(win))
            if hgt < 900:
                tiles.append([round(lng, 4), round(lat, 4), int(round(hgt))])
        lng += dlng
    lat += dlat
write_js("pool", dict(dlng=dlng, dlat=dlat, floor=278, tiles=tiles),
         "~500 m tiles over the basin with ground height (Copernicus DEM 30 m) for the 3D smog-pool layer")
