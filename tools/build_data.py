# perceptual "smoke" ramp: value -> rgba ; transparent where the contribution is negligible
GSTOPS = [(0.5, (255, 214, 140, 0)), (1.5, (255, 200, 110, 70)), (4, (255, 158, 64, 135)),
          (8, (240, 98, 46, 175)), (15, (205, 40, 70, 205)), (30, (140, 20, 110, 225)),
          (60, (80, 10, 90, 235))]
sv = np.array([s[0] for s in GSTOPS]); sc = np.array([s[1] for s in GSTOPS], float)


def colorize(a):
    out = np.zeros(a.shape + (4,), np.uint8)
    ok = np.isfinite(a)
    x = np.clip(np.where(ok, a, 0), sv[0], sv[-1])
    for ch in range(4):
        out[..., ch] = np.interp(x, sv, sc[:, ch]).astype(np.uint8)
    out[~ok] = 0
    return out


# palette PNG: quantize to discrete levels (log-spaced) -> tiny files, decoded natively by the browser
LEVELS = np.geomspace(0.6, 60, 40)               # bin edges, µg/m³
pal_rgba = colorize(np.concatenate([[0.0], np.sqrt(LEVELS[:-1] * LEVELS[1:]), [LEVELS[-1]]]))
pal_rgba[0] = 0                                  # index 0 = transparent / no data


def frame_png(a):
    idx = np.where(np.isfinite(a), np.searchsorted(LEVELS, np.nan_to_num(a, nan=0.0)), 0).astype(np.uint8)
    im = Image.fromarray(idx, "P")
    im.putpalette(pal_rgba[:, :3].astype(np.uint8).flatten().tolist())
    im.info["transparency"] = bytes(pal_rgba[:, 3].astype(np.uint8).tolist())
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True, transparency=bytes(pal_rgba[:, 3].astype(np.uint8).tolist()))
    return buf.getvalue()


from scipy.ndimage import gaussian_filter


def fill_holes(a, sigma=4):
    """Privacy-masked cells (NaN) -> normalized-convolution average of neighbours (display only)."""
    m = np.isfinite(a).astype(float)
    num = gaussian_filter(np.nan_to_num(a), sigma); den = gaussian_filter(m, sigma)
    filled = np.where(den > 0.05, num / np.maximum(den, 1e-6), np.nan)
    out = np.where(np.isfinite(a), a, filled)
    return out if sigma >= 12 else fill_holes(out, sigma * 3)


frames = []; size = 0; city_mean = []; filled = []
for hr in range(24):
    fv = fill_holes(v[hr]); filled.append(fv)
    b = frame_png(fv); size += len(b)
    frames.append("data:image/png;base64," + base64.b64encode(b).decode())
    city_mean.append(r1(np.nanmean(v[hr])))
filled = np.stack(filled)
to_utm = Transformer.from_crs("EPSG:4326", "EPSG:32633", always_xy=True)


def gral24(lng, lat):
    """Typical-day heating-smoke profile (24 UTC hours) at a point, or None outside the grid."""
    ex, ny = to_utm.transform(lng, lat)
    c = int((ex - (gx[0] - h)) // 30); r = int(((gy[0] + h) - ny) // 30)
    if not (0 <= r < filled.shape[1] and 0 <= c < filled.shape[2]):
        return None
    win = filled[:, max(r - 1, 0):r + 2, max(c - 1, 0):c + 2].reshape(24, -1)
    prof = np.nanmean(win, axis=1)
    return None if not np.isfinite(prof).all() else [r1(x) for x in prof]
print("gral png bytes", size)
write_js("gral", dict(
    corners=[[round(a, 6), round(b, 6)] for a, b in gcorners], w=int(v.shape[2]), h=int(v.shape[1]),
    stops=[[s[0], list(s[1])] for s in GSTOPS], hourMean=city_mean, frames=frames),
    "ARSO GRAL 30 m: PM10 contribution of small heating stoves, average per hour of day, heating season (model, 2021 meteorology)")

