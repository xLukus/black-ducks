"""Turn the ARSOhack data package into small, browser-ready JS data files.

Usage: python3 -I build_data.py <ARSOhack dir> <output dir>

Every file assigns to window.LjData.<name> so it loads with a plain <script>
tag (works from file:// and from any static server, no fetch/CORS needed).
"""
