"""Write public/data/forecast-history.js: the last 45 days of hourly PM10/PM2.5 for the three
ARSO Ljubljana stations, exactly as podatki.load_pm() returns them (clipped at 0, duplicates
keep the first). The forecast needs 30 days of history for its CAMS bias features; live hours
from the ARSO feed are added on top of this in the browser.

Run from the folder inside the ARSOhack checkout that holds podatki.py:
    python build_history.py <repo>/public/data/forecast-history.js
"""
import json
import sys

import numpy as np
import pandas as pd

from podatki import STATIONS, load_pm

DAYS = 45


def main():
    out = sys.argv[1]
    pm = load_pm()
    end = pm.time_utc.max()
    grid = pd.date_range(end.floor("h") - pd.Timedelta(days=DAYS), end.floor("h"), freq="h")
    data = {"t0": f"{grid[0]:%Y-%m-%dT%H:%M}Z", "n": len(grid), "stations": {}}
    for s in STATIONS:
        g = pm[pm.station_code == s].set_index("time_utc")[["pm10", "pm25"]].astype(float).reindex(grid)
        data["stations"][s] = {p: [None if not np.isfinite(v) else float(v) for v in g[p]] for p in ("pm10", "pm25")}
    with open(out, "w") as f:
        f.write("/* ARSO hourly PM10/PM2.5, Ljubljana stations, last 45 days of the ADA Hack 2026 package, "
                "unrounded, for the forecast model's history features. Generated by tools/forecast/build_history.py. Vir: ARSO. */\n")
        f.write(f"(window.LjData=window.LjData||{{}})['forecast-history']={json.dumps(data, separators=(',', ':'))};\n")
    print(out, data["t0"], data["n"])


if __name__ == "__main__":
    main()
